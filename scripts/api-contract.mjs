

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'

const AREAS = {
  'handlers.ts': 'Auth, onboarding & public economy',
  'personalHandlers.ts': 'Personal workspace (participant)',
  'orgHandlers.ts': 'Business / organization',
  'mmHandlers.ts': 'Market maker',
  'adminHandlers.ts': 'Admin governance',
  'profileHandlers.ts': 'Matching, reputation & public profiles',
  'roles.ts': 'Role activation (market maker applications, org invitations, create organisation)',
  'rfq.ts': 'RFQ, quotes & conversations',
  'settle.ts': 'Collective settlement of market rounds',
  'kyc.ts': 'Personal verification (email, KTP) & limits',
  'catalog.ts': 'Public listing catalog, price suggestion & direct market orders',
  'contracts.ts': 'Standing supply contracts',
}

const rows = []
for (const file of readdirSync('src/mocks').filter((f) => f in AREAS)) {
  const src = readFileSync(`src/mocks/${file}`, 'utf8')

  const prefix = src.match(/const api = \(path: string\) => `([^`$]*)\$\{path\}`/)?.[1] ?? '/api/v1'
  for (const m of src.matchAll(/http\.(get|post|put|patch|delete)\(api\('([^']*)'\)/g)) {
    rows.push({ area: AREAS[file], method: m[1].toUpperCase(), path: `${prefix}${m[2]}` })
  }
}

const out = [
  '# Ecopurnity API contract (frontend v1)',
  '',
  'Generated by `npm run contract` from the MSW handlers in `src/mocks/`. Each handler is the reference implementation of its endpoint: request/response shapes are the TypeScript types in `src/domain/` (start with `types.ts`), statuses are the enums in `src/domain/status.ts`, and state-machine rules live in `src/domain/{transaction,auction,org,marketRules,dispute}.ts`.',
  '',
  '## Conventions',
  '',
  '- Base path `/api/v1`, JSON, camelCase, times ISO 8601 UTC, money as integer Rupiah (`…Idr`), quantities `{ value, unit }`.',
  '- Session: httpOnly cookie. The frontend only depends on `GET /auth/me` (401 = signed out, 403 `account_suspended`).',
  '- Errors: `{ error: { code, message, fields? } }`. `fields` maps input names to messages and is shown under the inputs. Punitive admin/market-maker actions require `reason` (422 with `fields.reason` otherwise).',
  '- Lists: `?page=&pageSize=&q=&category=&region=&status=` → `{ data, meta: { page, pageSize, total } }` where paginated.',
  '- Every mutating governance, market-maker and org action must write an audit entry (`AuditEntry` in `types.ts`).',
  '- Realtime (WebSocket) messages: `{ channel, type, payload, ts }`. Channels: `public:stats`, `public:activity`, `auction:{id}` (`AuctionEvent`), `user:{id}:notifications` (`AppNotification`).',
  '- `/_mock/*` endpoints are local-only helpers (e.g. the email outbox) and are not part of the contract.',
  '',
  `## Endpoints (${rows.filter((r) => !r.path.includes('/_mock/')).length})`,
  '',
]
for (const area of Object.values(AREAS)) {
  const list = rows.filter((r) => r.area === area && !r.path.includes('/_mock/'))
  if (!list.length) continue
  out.push(`### ${area}`, '', '| Method | Path |', '| --- | --- |', ...list.map((r) => `| ${r.method} | \`${r.path}\` |`), '')
}
writeFileSync('docs/api-contract.md', out.join('\n'))
console.log(`docs/api-contract.md: ${rows.length} handlers`)
